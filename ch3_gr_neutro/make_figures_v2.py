# ----------------------------- Confusion ------------------------------------
def fig_confusion(primary: dict, out_dir: Path):
    """Two-panel figure: (left) raw co-occurrence count matrix with absolute numbers
    so a biologist can see how many cells were misclassified; (right) per-class
    precision/recall/F1 bar so the headline F1 in the table is reproducible.
    """
    pred = primary["pred"]
    cls_p = pred["test"]["class_logits"].sigmoid().numpy()
    y = pred["test"]["labels"].numpy().astype(int)
    classes = pred["class_names"]
    K = y.shape[1]
    e = primary.get("eval", {})
    thr = np.array(e.get("classification_tuned", {}).get("thresholds", [0.5] * K))
    pred_h = (cls_p >= thr[None, :]).astype(int)

    # Co-occurrence count matrix (multi-label: a cell with k true labels and m predicted
    # contributes 1 to k*m cells). On the diagonal: cells where true_k=1 AND pred_k=1.
    cm = np.zeros((K, K), dtype=int)
    for i in range(len(y)):
        true_k = np.where(y[i] == 1)[0]
        pred_k = np.where(pred_h[i] == 1)[0]
        for tk in true_k:
            for pk in pred_k:
                cm[tk, pk] += 1

    # Per-class binary precision/recall/F1 (these are what the headline table reports).
    from sklearn.metrics import precision_score, recall_score, f1_score
    prec = [precision_score(y[:, k], pred_h[:, k], zero_division=0) for k in range(K)]
    rec = [recall_score(y[:, k], pred_h[:, k], zero_division=0) for k in range(K)]
    f1 = [f1_score(y[:, k], pred_h[:, k], zero_division=0) for k in range(K)]
    n_pos = [int(y[:, k].sum()) for k in range(K)]

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5),
                              gridspec_kw={"width_ratios": [1.4, 1.0]})

    # Left: count matrix with absolute counts
    ax = axes[0]
    im = ax.imshow(cm, cmap="Blues")
    vmax = cm.max()
    for i in range(K):
        for j in range(K):
            color = "white" if cm[i, j] > vmax * 0.5 else "black"
            ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                    fontsize=10, color=color)
    ax.set_xticks(range(K)); ax.set_yticks(range(K))
    ax.set_xticklabels(classes, fontsize=8, rotation=30, ha="right")
    ax.set_yticklabels(classes, fontsize=8)
    ax.set_xlabel("Predicted class (multi-label, threshold-tuned)")
    ax.set_ylabel("True class")
    ax.set_title("Co-occurrence counts on test set\n(diagonal = correctly classified; off-diagonal = where the model got confused)")
    plt.colorbar(im, ax=ax, fraction=0.046, label="# (cell, true class, pred class) triples")

    # Right: per-class P / R / F1 grouped bars (these are the headline metrics).
    ax = axes[1]
    x = np.arange(K)
    width = 0.27
    ax.bar(x - width, prec, width=width, label="Precision", color="#1f77b4")
    ax.bar(x, rec, width=width, label="Recall", color="#ff7f0e")
    ax.bar(x + width, f1, width=width, label="F1", color="#2ca02c")
    for i, v in enumerate(f1):
        ax.text(x[i] + width, v + 0.01, f"{v:.2f}", ha="center", fontsize=7)
    ax.axhline(0.90, color="r", lw=0.8, ls="--", label="target 0.90")
    ax.set_xticks(x)
    ax.set_xticklabels([f"{c}\n(n={n_pos[i]})" for i, c in enumerate(classes)],
                        fontsize=8, rotation=30, ha="right")
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("Score (test, tuned thresholds)")
    ax.legend(loc="lower left", fontsize=8)
    ax.set_title("Per-class precision / recall / F1 (binary one-vs-rest)\nSame F1 numbers as the main results table")

    fig.tight_layout()
    fig.savefig(out_dir / "confusion_matrix.pdf")
    fig.savefig(out_dir / "confusion_matrix.png", dpi=150)
    plt.close(fig)
    print(f"[confusion] {out_dir}/confusion_matrix.pdf")


