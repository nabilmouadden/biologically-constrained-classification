# ----------------------------- Attention overlay ----------------------------
def attn_to_overlay(attn_kp: np.ndarray, grid_hw: tuple[int, int], out_size: int = 224):
    """One sample's K-th attention vector → upsampled, normalized heatmap on cell."""
    h, w = grid_hw
    a = attn_kp.reshape(h, w)
    a = (a - a.min()) / (a.max() - a.min() + 1e-9)
    return np.array(Image.fromarray((a * 255).astype(np.uint8))
                    .resize((out_size, out_size), Image.BILINEAR))


def fig_attention_overlay(primary: dict, out_dir: Path, data_root: Path,
                            filename_lookup: dict):
    """One row per class. Cell image | top-3 most relevant concepts (by class definition)
    overlaid on the same image. Picks cells where attention is concentrated on the
    central cell region (not on background RBCs/empty space).
    """
    pred = primary["pred"]
    if "attn" not in pred["test"]:
        print("[attn_overlay] no attn maps; skipping")
        return
    attn = pred["test"]["attn"].numpy()             # (N, K, P)
    cls_p = pred["test"]["class_logits"].sigmoid().numpy()
    con_p = pred["test"]["concept_logits"].sigmoid().numpy()
    y = pred["test"]["labels"].numpy().astype(int)
    e = primary.get("eval", {})
    thr = np.array(e.get("classification_tuned", {}).get("thresholds",
                                                            [0.5] * len(pred["class_names"])))
    pred_h = (cls_p >= thr[None, :]).astype(int)
    no_pred = pred_h.sum(axis=1) == 0
    if no_pred.any():
        ratio = cls_p / thr[None, :]
        for i in np.where(no_pred)[0]:
            pred_h[i, int(np.argmax(ratio[i]))] = 1
    classes = pred["class_names"]
    concepts = pred["concepts"]
    P = attn.shape[2]
    side = int(round(P ** 0.5))
    grid_hw = (side, side)

    # Build a "centrality" score for each (cell, concept). Cell images are
    # centered, so the cell occupies roughly the central 50% of the patch grid.
    # High score = attention concentrates on cell, not background.
    h, w = grid_hw
    cy_lo, cy_hi = int(h * 0.20), int(h * 0.80)
    cx_lo, cx_hi = int(w * 0.20), int(w * 0.80)
    center_mask = np.zeros((h, w), dtype=bool)
    center_mask[cy_lo:cy_hi, cx_lo:cx_hi] = True
    center_mask_flat = center_mask.flatten()
    # centrality_kc[i, c] = fraction of total attention inside the central window
    a_norm = attn / (attn.sum(axis=2, keepdims=True) + 1e-9)
    centrality = a_norm[:, :, center_mask_flat].sum(axis=2)   # (N, K)

    # Identify which concepts are "defining" for each class (docx |dev from baseline| ≥ 0.1).
    cfg_path = HERE / "concept_config_gr_neutro.json"
    cfg = json.loads(cfg_path.read_text())
    class_concept = np.array(cfg["class_to_concept_matrix"]["matrix"])
    baseline = class_concept[cfg.get("normal_class_index", 0)]
    rel_per_class = np.abs(class_concept - baseline)   # (n_classes, n_concepts)
    # If Normal class — all values are baseline; pick the highest-magnitude concepts among those
    # actually present (lobulation, granule_density, etc. that have value > 0.4).
    rel_per_class[0] = np.abs(class_concept[0] - 0.0)

    # Pick one CORRECTLY classified cell per class, scoring by attention centrality
    # only (not by "defining concept"). For each candidate cell we'll later show
    # the model's OWN top-3 predicted concepts (whichever they are, p>=0.9), so
    # attention maps are guaranteed to fire on something the model thinks is present.
    picked = []
    for k, cls in enumerate(classes):
        mask = (y[:, k] == 1) & np.all(pred_h == y, axis=1)
        idxs = np.where(mask)[0]
        if len(idxs) == 0:
            mask = (y[:, k] == 1) & (pred_h[:, k] == 1)
            idxs = np.where(mask)[0]
        if len(idxs) == 0:
            continue
        # Score by: (a) need >=2 concepts predicted with prob>=0.9 (so we have
        # something focused to show), (b) centrality of top concepts.
        n_high_prob = (con_p[idxs] >= 0.9).sum(axis=1)
        # Mean centrality across the top-K predicted concepts (K=3 if >=3 high-prob, else all)
        mean_centrality = []
        for ci_local, ci in enumerate(idxs):
            top_pred_concepts = np.argsort(-con_p[ci])[:3]
            mean_centrality.append(centrality[ci, top_pred_concepts].mean())
        mean_centrality = np.array(mean_centrality)
        # Score: prefer >=2 high-prob concepts; among them, max centrality.
        score = mean_centrality + 0.5 * (n_high_prob >= 2).astype(float) + 0.3 * cls_p[idxs, k]
        best = idxs[int(np.argmax(score))]
        picked.append((cls, int(best)))

    n_top_concepts = 3
    fig, axes = plt.subplots(len(picked), 1 + n_top_concepts,
                              figsize=((1 + n_top_concepts) * 2.2, 2.4 * len(picked)))
    if len(picked) == 1:
        axes = axes[None, :]
    for r, (cls_name, ci) in enumerate(picked):
        fname = filename_lookup.get(int(pred["test_idx"][ci]), None)
        cand = list(data_root.rglob(fname)) if fname else []
        img = Image.open(cand[0]).convert("RGB").resize((224, 224)) if cand else Image.new("RGB", (224,224), (128,128,128))
        ax0 = axes[r, 0]
        ax0.imshow(img)
        ax0.set_xticks([]); ax0.set_yticks([])
        ax0.set_ylabel(cls_name, fontsize=10, rotation=0, ha="right", va="center")
        if r == 0:
            ax0.set_title("cell image", fontsize=10)
        # Show the cell's OWN top-3 predicted concepts (not textbook "defining" —
        # this guarantees attention fires on something the model thinks is present).
        top3 = np.argsort(-con_p[ci])[:n_top_concepts]
        for j, kc in enumerate(top3):
            heat = attn_to_overlay(attn[ci, kc], grid_hw)
            ax = axes[r, j + 1]
            ax.imshow(img)
            ax.imshow(heat, cmap="jet", alpha=0.45)
            ax.set_xticks([]); ax.set_yticks([])
            label = concepts[kc].replace("_", "\n")
            cell_centrality = centrality[ci, kc]
            ax.set_title(f"{label}\np={con_p[ci, kc]:.2f}  (centr.={cell_centrality:.2f})", fontsize=7)
    fig.suptitle("Where the model looks per defining concept (cells filtered for centrality)", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_dir / "attention_overlay.pdf")
    fig.savefig(out_dir / "attention_overlay.png", dpi=150)
    plt.close(fig)
    print(f"[attn_overlay] {out_dir}/attention_overlay.pdf  rows={len(picked)}")


