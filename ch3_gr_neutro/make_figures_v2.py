def fig_main_table(runs: dict, out_dir: Path):
    """One row per run; columns = the four target metrics + per-class + per-concept rollups.

    Tuned values from eval.json preferred over summary.json raw.
    """
    rows = []
    classes = next(iter(runs.values()))["pred"]["class_names"]
    concepts = next(iter(runs.values()))["pred"]["concepts"]
    for tag, r in runs.items():
        e = r["eval"]
        s = r["summary"]
        ct = e.get("classification_tuned", {})
        co = e.get("concept_tuned", {})
        co_pc = co.get("per_concept_f1", [])
        ct_pc = ct.get("per_class_f1", [])
        row = dict(run=tag,
                    weighted_f1=ct.get("weighted_f1", float("nan")),
                    macro_f1=ct.get("macro_f1", float("nan")),
                    mean_concept_f1=co.get("mean_concept_f1", float("nan")),
                    coverage_at_0p05=e.get("conformal", {}).get("marginal_positive_coverage", float("nan")),
                    probe_weighted_f1=e.get("completeness_probe", {}).get("weighted_f1", float("nan")),
                    probe_subset_acc=e.get("completeness_probe", {}).get("subset_accuracy", float("nan")),
                    min_class_f1=float(np.min(ct_pc)) if ct_pc else float("nan"),
                    min_concept_f1=float(np.min(co_pc)) if co_pc else float("nan"),
                    n_classes_above_0p90=int(sum(1 for f in ct_pc if f >= 0.90)),
                    n_concepts_above_0p90=int(sum(1 for f in co_pc if f >= 0.90)),
                    )
        rows.append(row)
    csv_path = out_dir / "main_results_table.csv"
    fields = list(rows[0].keys())
    with open(csv_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        rows.sort(key=lambda r: r.get("weighted_f1") or -1, reverse=True)
        w.writerows(rows)
    # Per-class breakdown CSV — one row per (run, class) for easy filtering
    pc_path = out_dir / "per_class_breakdown.csv"
    with open(pc_path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["run", "class", "F1_tuned", "F1_at_0p90"])
        for tag, r in runs.items():
            f1s = r["eval"].get("classification_tuned", {}).get("per_class_f1", [])
            for c, f1 in zip(classes, f1s):
                w.writerow([tag, c, f"{f1:.4f}", "yes" if f1 >= 0.90 else "no"])
    pc_concept_path = out_dir / "per_concept_breakdown.csv"
    with open(pc_concept_path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["run", "concept", "F1_tuned", "F1_at_0p90"])
        for tag, r in runs.items():
            f1s = r["eval"].get("concept_tuned", {}).get("per_concept_f1", [])
            for c, f1 in zip(concepts, f1s):
                w.writerow([tag, c, f"{f1:.4f}", "yes" if f1 >= 0.90 else "no"])
    print(f"[per_class_csv] {pc_path}\n[per_concept_csv] {pc_concept_path}")
    # LaTeX with target line
    tex = ["% Main results — ≥0.90 means hit target. Generated by make_figures_v2.py."]
    tex.append("\\begin{tabular}{lcccccc}\\toprule")
    tex.append("Run & W-F1 & Concept F1 & Cov\\,$\\alpha=.05$ & Probe W-F1 & "
                "min cls F1 & min con F1 \\\\\\midrule")
    for r in rows:
        def f(v):
            return "-" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.3f}"
        tag_safe = r["run"].replace("_", "\\_")
        tex.append("\\texttt{" + tag_safe + "} & "
                    f"{f(r['weighted_f1'])} & {f(r['mean_concept_f1'])} & "
                    f"{f(r['coverage_at_0p05'])} & {f(r['probe_weighted_f1'])} & "
                    f"{f(r['min_class_f1'])} & {f(r['min_concept_f1'])} \\\\")
    tex.append("\\bottomrule\\end{tabular}")
    (out_dir / "main_results_table.tex").write_text("\n".join(tex))

    # Render the same table as a PDF using matplotlib (no LaTeX dependency).
    cell_text = []
    headers = ["Run", "W-F1", "Concept F1", "Cov α=.05", "Probe W-F1",
                "min cls F1", "min con F1", "n cls ≥0.9", "n con ≥0.9"]
    def f(v):
        return "—" if v is None or (isinstance(v, float) and np.isnan(v)) else f"{v:.3f}"
    for row in rows:
        cell_text.append([
            row["run"], f(row["weighted_f1"]), f(row["mean_concept_f1"]),
            f(row["coverage_at_0p05"]), f(row["probe_weighted_f1"]),
            f(row["min_class_f1"]), f(row["min_concept_f1"]),
            str(row["n_classes_above_0p90"]), str(row["n_concepts_above_0p90"]),
        ])
    fig, ax = plt.subplots(figsize=(13, max(2.5, 0.5 * (len(rows) + 1))))
    ax.axis("off")
    table = ax.table(cellText=cell_text, colLabels=headers, loc="center",
                      cellLoc="center", colLoc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(8)
    table.scale(1.0, 1.4)
    # Color the header row + best row
    for j in range(len(headers)):
        table[(0, j)].set_facecolor("#cccccc")
        table[(0, j)].set_text_props(weight="bold")
    # Highlight best row (highest weighted_f1)
    best_row = max(range(len(rows)), key=lambda i: rows[i].get("weighted_f1") or -1)
    for j in range(len(headers)):
        table[(best_row + 1, j)].set_facecolor("#dff0d8")
    fig.suptitle("GR-Neutro × concept adapter — main results", fontsize=11)
    fig.tight_layout()
    fig.savefig(out_dir / "main_results_table.pdf", bbox_inches="tight")
    fig.savefig(out_dir / "main_results_table.png", dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"[main_table] {csv_path}, .pdf, .png")
    return rows


def fig_per_class_breakdown(runs: dict, out_dir: Path):
    """Per-class F1 bar chart with target line. Annotates which classes hit ≥0.90."""
    classes = next(iter(runs.values()))["pred"]["class_names"]
    fig, ax = plt.subplots(figsize=(9, max(3.5, 0.7 * len(runs))))
    n_runs = len(runs)
    width = 0.8 / n_runs
    x = np.arange(len(classes))
    palette = plt.get_cmap("tab10")
    for i, (tag, r) in enumerate(runs.items()):
        f1s = r["eval"].get("classification_tuned", {}).get("per_class_f1", [])
        if not f1s:
            continue
        bars = ax.bar(x + i * width, f1s, width=width, label=tag, color=palette(i))
        for bx, val in zip(bars, f1s):
            if val >= 0.90:
                ax.text(bx.get_x() + bx.get_width()/2, val + 0.005, "✓",
                        ha="center", fontsize=9, color="green")
    ax.axhline(0.90, color="r", ls="--", lw=1, label="target 0.90")
    ax.set_xticks(x + width * (n_runs - 1) / 2)
    ax.set_xticklabels(classes, rotation=20, ha="right")
    ax.set_ylabel("Per-class F1 (test, tuned thresholds)")
    ax.set_ylim(0, 1.05)
    ax.legend(loc="lower right", fontsize=8)
    ax.set_title("Classification F1 per class — target ≥ 0.90")
    fig.tight_layout()
    fig.savefig(out_dir / "per_class_f1.pdf")
    fig.savefig(out_dir / "per_class_f1.png", dpi=150)
    plt.close(fig)
    print(f"[per_class] {out_dir}/per_class_f1.pdf")


