def _load_image(test_idx, ci, filename_lookup, data_root):
    fname = filename_lookup.get(int(test_idx[ci]), None)
    if not fname:
        return None
    cand = list(data_root.rglob(fname))
    if not cand:
        return None
    return Image.open(cand[0]).convert("RGB")


def fig_classified_examples(primary: dict, out_dir: Path, data_root: Path,
                              filename_lookup: dict, k_per_class: int = 2):
    """For each class, show k correctly-classified examples + a horizontal bar of
    predicted concept probabilities. Uses tuned thresholds + argmax fallback.
    """
    pred = primary["pred"]
    cls_p = pred["test"]["class_logits"].sigmoid().numpy()
    con_p = pred["test"]["concept_logits"].sigmoid().numpy()
    y = pred["test"]["labels"].numpy().astype(int)
    classes = pred["class_names"]
    concepts = pred["concepts"]
    test_idx = pred["test_idx"]
    e = primary.get("eval", {})
    thr = np.array(e.get("classification_tuned", {}).get("thresholds",
                                                            [0.5] * len(classes)))
    pred_h = (cls_p >= thr[None, :]).astype(int)
    no_pred = pred_h.sum(axis=1) == 0
    if no_pred.any():
        ratio = cls_p / thr[None, :]
        for i in np.where(no_pred)[0]:
            pred_h[i, int(np.argmax(ratio[i]))] = 1

    # Pick examples
    examples = []
    for k, cls in enumerate(classes):
        # correct: predictions match labels exactly AND this class is positive
        mask = (y[:, k] == 1) & np.all(pred_h == y, axis=1)
        idxs = np.where(mask)[0]
        if len(idxs) >= k_per_class:
            picks = idxs[:k_per_class]
        else:
            picks = idxs[:k_per_class] if len(idxs) > 0 else []
        for ci in picks:
            examples.append((cls, int(ci)))

    if not examples:
        return
    rows = len(examples)
    fig, axes = plt.subplots(rows, 2, figsize=(11, 2.0 * rows),
                              gridspec_kw={"width_ratios": [1.1, 2.5]})
    if rows == 1:
        axes = axes[None, :]
    for r, (cls_name, ci) in enumerate(examples):
        img = _load_image(test_idx, ci, filename_lookup, data_root)
        if img is not None:
            axes[r, 0].imshow(img)
        axes[r, 0].set_xticks([]); axes[r, 0].set_yticks([])
        # Show ALL active labels via xlabel below image
        truth_classes = ", ".join(classes[k] for k in np.where(y[ci]==1)[0])
        axes[r, 0].set_xlabel(truth_classes, fontsize=9, labelpad=4)
        if r == 0:
            axes[r, 0].set_title("Cell (true label)", fontsize=10)
        # Concept bar chart
        ax = axes[r, 1]
        order = np.argsort(con_p[ci])[::-1]
        bars = ax.barh(range(len(concepts)), con_p[ci][order], color="steelblue")
        for bx, v in zip(bars, con_p[ci][order]):
            ax.text(min(v + 0.01, 0.97), bx.get_y() + bx.get_height()/2, f"{v:.2f}",
                    va="center", fontsize=7)
        ax.axvline(0.5, color="k", lw=0.5, ls="--")
        ax.set_yticks(range(len(concepts)))
        ax.set_yticklabels([concepts[i].replace("_", " ") for i in order], fontsize=8)
        ax.invert_yaxis()
        ax.set_xlim(0, 1.05)
        if r == 0:
            ax.set_title("Predicted concept probabilities", fontsize=10)
    fig.suptitle("Correctly classified cells with predicted concepts", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_dir / "correct_examples.pdf")
    fig.savefig(out_dir / "correct_examples.png", dpi=150)
    plt.close(fig)
    print(f"[correct] {out_dir}/correct_examples.pdf  n={rows}")


def fig_misclassified_examples(primary: dict, out_dir: Path, data_root: Path,
                                  filename_lookup: dict, n: int = 12):
    """Misclassified test cells with TRUE vs PREDICTED label and concept probs.
    Biologist can read WHY (which concepts predicted differ from typical class profile).

    Uses tuned per-class thresholds when available so what's shown matches the
    headline F1 numbers. If no class crosses its threshold for a cell, we fall back
    to the argmax class — every cell IS some class biologically.
    """
    pred = primary["pred"]
    cls_p = pred["test"]["class_logits"].sigmoid().numpy()
    con_p = pred["test"]["concept_logits"].sigmoid().numpy()
    y = pred["test"]["labels"].numpy().astype(int)
    classes = pred["class_names"]
    concepts = pred["concepts"]
    test_idx = pred["test_idx"]

    # Apply tuned thresholds (if available) so the predictions match the headline F1.
    e = primary.get("eval", {})
    thr = np.array(e.get("classification_tuned", {}).get("thresholds",
                                                            [0.5] * len(classes)))
    pred_h = (cls_p >= thr[None, :]).astype(int)
    # Fallback: if no class crosses its threshold, assign argmax(prob/threshold).
    no_pred = pred_h.sum(axis=1) == 0
    if no_pred.any():
        ratio = cls_p / thr[None, :]
        for i in np.where(no_pred)[0]:
            pred_h[i, int(np.argmax(ratio[i]))] = 1

    wrong = np.where(np.any(pred_h != y, axis=1))[0]
    if len(wrong) == 0:
        return
    # Try to balance across rare classes — pick at least 1 from each rare class
    # where the cell was misclassified. Fill remainder with random.
    rng = np.random.default_rng(0)
    rare_classes = [k for k, cls in enumerate(classes) if (y[:, k] == 1).sum() < 50]
    chosen = []
    for k in rare_classes:
        cands = [w for w in wrong if y[w, k] == 1]
        if cands:
            chosen.append(int(rng.choice(cands)))
    remain = [w for w in wrong if w not in chosen]
    if len(chosen) < n and remain:
        extras = rng.choice(remain, size=min(n - len(chosen), len(remain)), replace=False)
        chosen.extend([int(x) for x in extras])
    chosen = chosen[:n]
    if not chosen:
        return
    rows = len(chosen)
    # Wider figure, left margin for labels.
    fig, axes = plt.subplots(rows, 2, figsize=(11, 2.2 * rows),
                              gridspec_kw={"width_ratios": [1.1, 2.5]})
    if rows == 1:
        axes = axes[None, :]
    for r, ci in enumerate(chosen):
        img = _load_image(test_idx, ci, filename_lookup, data_root)
        if img is not None:
            axes[r, 0].imshow(img)
        axes[r, 0].set_xticks([]); axes[r, 0].set_yticks([])
        truth = ", ".join(classes[k] for k in np.where(y[ci] == 1)[0]) or "(none)"
        predicted = ", ".join(classes[k] for k in np.where(pred_h[ci] == 1)[0]) or "(none)"
        # Use xlabel below image for the label, keeping vertical layout clean
        axes[r, 0].set_xlabel(f"TRUE: {truth}\nPRED: {predicted}",
                                 fontsize=8, labelpad=4)
        if r == 0:
            axes[r, 0].set_title("Cell", fontsize=10)
        # Concept bar
        ax = axes[r, 1]
        order = np.argsort(con_p[ci])[::-1]
        # Highlight bars where predicted differs from class-typical (deviation from
        # docx baseline) — color cue for biologist
        concept_vals = con_p[ci][order]
        bars = ax.barh(range(len(concepts)), concept_vals, color="steelblue")
        # Red horizontal at p>=0.5 + concept that disagrees with majority truth class
        if np.any(y[ci] == 1):
            true_class_idx = int(np.argmax(y[ci]))
            cfg_path = HERE / "concept_config_gr_neutro.json"
            cfg = json.loads(cfg_path.read_text())
            class_concept_arr = np.array(cfg["class_to_concept_matrix"]["matrix"])
            true_profile_hard = (class_concept_arr[true_class_idx] >= 0.5).astype(int)
            for j, idx_orig in enumerate(order):
                pred_pos = concept_vals[j] >= 0.5
                expected_pos = true_profile_hard[idx_orig] == 1
                if pred_pos != expected_pos:
                    bars[j].set_color("#d62728")
        for bx, v in zip(bars, concept_vals):
            ax.text(min(v + 0.01, 0.97), bx.get_y() + bx.get_height()/2, f"{v:.2f}",
                    va="center", fontsize=7)
        ax.axvline(0.5, color="k", lw=0.5, ls="--")
        ax.set_yticks(range(len(concepts)))
        ax.set_yticklabels([concepts[i].replace("_", " ") for i in order], fontsize=8)
        ax.invert_yaxis()
        ax.set_xlim(0, 1.05)
        if r == 0:
            ax.set_title("Predicted concept probabilities (red = mismatch with TRUE class profile)", fontsize=9)
    fig.suptitle("Misclassified test cells — what the model 'saw'", fontsize=12)
    fig.tight_layout()
    fig.savefig(out_dir / "misclassified_examples.pdf")
    fig.savefig(out_dir / "misclassified_examples.png", dpi=150)
    plt.close(fig)
    print(f"[misclass] {out_dir}/misclassified_examples.pdf  n={rows}")


