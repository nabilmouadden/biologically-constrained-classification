def load_run(tag: str, root: Path):
    rd = root / tag
    out = dict(tag=tag, run_dir=rd)
    out["pred"] = torch.load(rd / "predictions.pt", map_location="cpu", weights_only=False)
    out["summary"] = json.loads((rd / "summary.json").read_text())
    if (rd / "eval.json").exists():
        out["eval"] = json.loads((rd / "eval.json").read_text())
    else:
        out["eval"] = {}
    log_path = rd / "training_log.csv"
    if log_path.exists():
        out["log"] = list(csv.reader(open(log_path)))
    else:
        out["log"] = None
    return out


